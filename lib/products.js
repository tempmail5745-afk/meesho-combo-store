export function getProductById(id) {
  const numId = parseInt(id, 10);
  return ALL_PRODUCTS.find(p => p.id === numId) || ALL_PRODUCTS[0];
}

export function getRelatedProducts(id, limit = 4) {
  const numId = parseInt(id, 10);
  const current = getProductById(numId);
  const sameCategory = ALL_PRODUCTS.filter(p => p.id !== numId && (p.category === current.category || p.priceTier === current.priceTier));
  if (sameCategory.length >= limit) return sameCategory.slice(0, limit);
  const others = ALL_PRODUCTS.filter(p => p.id !== numId && !sameCategory.includes(p));
  return [...sameCategory, ...others].slice(0, limit);
}
